'use strict';
// unread.js — «этот ответ человек ещё не видел».
//
// Перезапуск гасит вкладку по расходу контекста и спрашивает у агента разрешения (restart.js).
// Агент разрешает по состоянию РАБОТЫ: не стою ли я на середине неделимого, всё ли сохранено.
// Про человека он при этом судить не может, и это не лень, а устройство: в своём разговоре он
// видит написанный ответ и считает дело сделанным — ровно так же, как считал бы, если бы этот
// ответ прочитали. Разницы «сказано» и «услышано» изнутри разговора не существует.
//
// А разница есть, и живой случай простой: человек спросил, агент ответил, человек в этот момент
// смотрел в другую вкладку, и через полминуты автомат снёс сессию. Ответ не потерян физически —
// он в стенограмме, — но человек его не увидит: свежий агент про прошлый разговор не знает, а
// экран уже чистый. Спрашивать было незачем.
//
// Поэтому признак держит ПРИЛОЖЕНИЕ, а не агент: только оно знает, куда человек смотрел.
//
// Правило владельца (2026-08-13): ждём столько, сколько нужно, без срока давности. «Если я задал
// вопрос — значит я жду ответ, и он повлияет на разработку. Если я спросил и ушёл спать — моя
// вина». Поэтому здесь нет ни таймера, ни автосдачи: пометка снимается только человеком — кроме
// одного случая, и он не про человека вовсе: служебный ход сворма её и не ставит (onSwarmAsk).
//
// Чистый Node и отдельный файл — по правилу репозитория: решения, которые можно проверить без
// Electron, живут под тестом. Руки (IPC, детектор, снимок для перезапуска) — в main.js.
(function (root, factory) {
  const api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.SWARM_UNREAD = api;
})(typeof self !== 'undefined' ? self : this, function () {

// Состояние на вкладку:
//   asked  — ход идёт по просьбе ЧЕЛОВЕКА, то есть его итога кто-то ждёт;
//   at     — когда лёг непрочитанный ответ (0 — непрочитанного нет);
//   strict — ответ лёг человеку прямо в глаза, и взглядом его уже не «прочитать» (см. onViewed);
//   svc    — открыт служебный круг сворма: он сам спросил у агента про перезапуск и ждёт (см. onSwarmAsk).
function initial() {
  return { asked: false, at: 0, strict: false, svc: false };
}

// Вкладку перезапустили: новый агент, новый разговор. Непрочитанное прошлой сессии умирает
// вместе с ней — держать пометку дальше значит запереть уже другую вкладку чужим долгом.
function reset() {
  return initial();
}

// Человек отправил в эту вкладку сообщение — с клавиатуры или из телеги. Здесь сходятся оба
// события сразу, и это не совпадение: отправленное сообщение ОДНОВРЕМЕННО значит «прошлое я
// прочитал» (иначе бы не отвечал) и «жду ответа на новое».
function onHumanSend(st) {
  // И служебный круг сворма перестаёт быть служебным: раз человек написал, дальше в этой вкладке
  // говорят с ним, и следующий итог — уже его (см. onSwarmAsk).
  return { asked: true, at: 0, strict: false, svc: false };
}

// Сворм напечатал агенту служебное: просьбу о перезапуске — или принял на неё разрешение и ждёт
// спокойного мига, чтобы его исполнить. Всё, что агент говорит внутри этого круга, адресовано
// СВОРМУ, а не человеку.
//
// Без этой отметки вкладка запирала себя собственной служебной перепиской, и живьём это выглядело
// так: агент разрешил перезапуск словами «вкладку можно гасить», сворм принял разрешение — и тут
// же сам себе его запретил, потому что конец того же хода лёг пометкой «ответ, которого человек не
// видел». Спрашивать было не у кого: перезапуск ждал, пока человек ответит на «от тебя ничего».
//
// Раньше здесь полагались на одно `asked` — «ход начал не человек, значит и помечать нечего», — но
// ожидание человека живёт дольше одного хода: вкладка, отчитывающаяся «ничего, жду фиксы», не
// закрывает его вовсе (см. onTurnEnd), и служебный круг попадал под чужую, давно открытую просьбу.
//
// `since` — когда агент ПОЗВАЛ перезапуск сам, файлом (мгновение записи зова). Круг он при этом
// открывает задним числом: сворм узнаёт о файле тактом, а к тому времени прощальный ход агента
// («эстафета записана, перезапускаюсь») уже кончился и уже лёг пометкой. Отметка `svc` от этого не
// спасает — она про ходы, которые кончатся ПОСЛЕ неё, а тут спасать надо предыдущий.
//
// Живой случай (24.08, вкладка fastio 4): файл лёг в 22:14:22, ход кончился в 22:14:36, сворм
// принял зов в 22:14:47 — и упёрся в пометку от этого самого хода. Часы разрешения под
// непрочитанным намеренно стоят, так что вкладка простояла с готовой строкой запуска до утра.
//
// Поэтому пометку, вставшую не раньше зова, снимаем: её ставил служебный ход. Всё, что старше,
// остаётся — это чужой долг, и правило владельца про него в силе (ждём глаз, без срока давности).
function onSwarmAsk(st, o) {
  const s = { ...(st || initial()), svc: true };
  const since = Number(o && o.since) || 0;
  if (since && s.at && s.at >= since) return { ...s, at: 0, strict: false };
  return s;
}

// Служебный круг закрылся: ответ прочитан, перезапуск исполнен или отменён. Дальше вкладка снова
// разговаривает с человеком, и её итоги снова его.
function onSwarmIdle(st) {
  return { ...(st || initial()), svc: false };
}

// Ход кончился. Помечаем только тот, чьего итога кто-то ждёт, а ждать может лишь тот, кто
// спрашивал: без отправленного человеком сообщения ход помечать не за что. Этим отсекается ночной
// прогон, разбуженный расписанием или фоновой задачей, — человек его не начинал.
//
// Служебный круг сворма отсекается отдельной отметкой, и одного `asked` для него не хватало: см.
// onSwarmAsk.
//
// `done` — ход закончен совсем (агент замолчал), а не ушёл в фоновое ожидание. «Ничего, жду
// замер стенда» — это тоже сказанное человеку, и пометку оно ставит, но ожидание не закрывает:
// настоящий ответ будет потом, и вот он-то и нужен человеку больше всего.
//
// `needsYou` — агент кончил ход тем, что от человека ЧТО-ТО нужно: позвал вопросом, решением,
// разрешением. Отсюда берётся строгость, и вот почему она не может стоять на одном взгляде.
// «Ответ лёг тебе прямо в глаза» имеет смысл, пока ответа ждут: тогда единственное честное
// подтверждение — твоё слово. А ход, кончившийся словами «Сейчас от тебя: ничего», отвечать не
// просит вовсе — и строгая пометка на нём превращалась в замок без ключа: снять её мог только
// ответ, которого агент сам не ждал. Вкладка стояла с готовым разрешением на перезапуск, пока
// человек не напишет ей что-нибудь просто так.
function onTurnEnd(st, o) {
  const opts = o || {};
  if (!st || !st.asked) return st || initial();
  if (st.svc) return st;
  const needsYou = !!opts.needsYou;
  // Сказанное «мне от тебя ничего не нужно» на глазах у человека прочитано и есть: он смотрел в
  // эту вкладку в тот самый миг, когда текст в ней появился, и ждать ему нечего.
  if (!needsYou && opts.viewing) return { ...st, asked: !opts.done, at: 0, strict: false };
  return { asked: !opts.done, at: Number(opts.now) || 1, strict: needsYou && !!opts.viewing, svc: false };
}

// Человек СМОТРИТ на эту вкладку: она активна, и окно приложения в фокусе.
//
// Взгляд считается прочтением только в мягком случае — когда ответ лёг, пока человек смотрел
// куда-то ещё. Тогда «переключиться на вкладку» это настоящее действие: он пришёл читать.
//
// Если же агентом ЗАДАН ВОПРОС и лёг он прямо перед открытой вкладкой, переключаться человеку
// неоткуда, и такой «взгляд» пришёл бы в тот же миг, в который встала пометка, — сторож снимал бы
// сам себя. Здесь остаётся единственное честное подтверждение: ответ человека (см. onTurnEnd).
function onViewed(st) {
  if (!st || !st.at || st.strict) return st || initial();
  return { ...st, at: 0, strict: false };
}

// Висит ли непрочитанное. Это и есть то, что держит перезапуск (см. restart.askable).
function isUnread(st) {
  return !!(st && st.at);
}

return { initial, reset, onHumanSend, onSwarmAsk, onSwarmIdle, onTurnEnd, onViewed, isUnread };

});
