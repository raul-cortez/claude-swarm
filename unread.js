'use strict';
// unread.js — «этот ответ человек ещё не видел».
//
// Перезапуск гасит вкладку по расходу контекста и спрашивает у агента разрешения (restart.js).
// Агент разрешает по состоянию РАБОТЫ: не стою ли я на середине неделимого, всё ли сохранено.
// Про человека он при этом судить не может, и это не лень, а устройство: в своём разговоре он
// видит написанный ответ и считает дело сделанным — ровно так же, как считал бы, если бы этот
// ответ прочитали. Разницы «сказано» и «услышано» изнутри разговора не существует.
//
// А разница есть, и живой случай простой: человек спросил, агент ответил, человек в этот момент
// смотрел в другую вкладку, и через полминуты автомат снёс сессию. Ответ не потерян физически —
// он в стенограмме, — но человек его не увидит: свежий агент про прошлый разговор не знает, а
// экран уже чистый. Спрашивать было незачем.
//
// Поэтому признак держит ПРИЛОЖЕНИЕ, а не агент: только оно знает, куда человек смотрел.
//
// Правило владельца (2026-08-13): ждём столько, сколько нужно, без срока давности. «Если я задал
// вопрос — значит я жду ответ, и он повлияет на разработку. Если я спросил и ушёл спать — моя
// вина». Поэтому здесь нет ни таймера, ни автосдачи: пометка снимается только человеком.
//
// Чистый Node и отдельный файл — по правилу репозитория: решения, которые можно проверить без
// Electron, живут под тестом. Руки (IPC, детектор, снимок для перезапуска) — в main.js.
(function (root, factory) {
  const api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.SWARM_UNREAD = api;
})(typeof self !== 'undefined' ? self : this, function () {

// Состояние на вкладку:
//   asked  — ход идёт по просьбе ЧЕЛОВЕКА, то есть его итога кто-то ждёт;
//   at     — когда лёг непрочитанный ответ (0 — непрочитанного нет);
//   strict — ответ лёг человеку прямо в глаза, и взглядом его уже не «прочитать» (см. onViewed).
function initial() {
  return { asked: false, at: 0, strict: false };
}

// Вкладку перезапустили: новый агент, новый разговор. Непрочитанное прошлой сессии умирает
// вместе с ней — держать пометку дальше значит запереть уже другую вкладку чужим долгом.
function reset() {
  return initial();
}

// Человек отправил в эту вкладку сообщение — с клавиатуры или из телеги. Здесь сходятся оба
// события сразу, и это не совпадение: отправленное сообщение ОДНОВРЕМЕННО значит «прошлое я
// прочитал» (иначе бы не отвечал) и «жду ответа на новое».
function onHumanSend(st) {
  return { asked: true, at: 0, strict: false };
}

// Ход кончился. Помечаем только тот, чьего итога кто-то ждёт, а ждать может лишь тот, кто
// спрашивал: без отправленного человеком сообщения ход помечать не за что. Одним этим условием
// отсекаются оба лишних случая, и не по отдельности, а разом:
//   • ночной прогон, разбуженный расписанием или фоновой задачей, — человек его не начинал;
//   • служебный ход самого сворма, который печатает агенту просьбу о перезапуске. Пометь мы
//     его — вкладка запирала бы себя собственной служебной перепиской, и перезапуск не
//     случился бы никогда.
// Отдельного признака «ход завёл сворм» здесь нет намеренно: он был бы не только лишним, но и
// вредным. Такая метка живёт дольше одного хода (агент отвечает «спроси через сорок минут», и
// круг не закрывается), и повисни она — следующий, уже настоящий ответ человеку остался бы
// непомеченным. А случай, где человек успел вмешаться в служебный круг, она разбирала бы
// НЕВЕРНО: раз человек написал — итога ждут, и пометка нужна.
//
// `done` — ход закончен совсем (агент замолчал), а не ушёл в фоновое ожидание. «Ничего, жду
// замер стенда» — это тоже сказанное человеку, и пометку оно ставит, но ожидание не закрывает:
// настоящий ответ будет потом, и вот он-то и нужен человеку больше всего.
function onTurnEnd(st, o) {
  const opts = o || {};
  if (!st || !st.asked) return st || initial();
  return { asked: !opts.done, at: Number(opts.now) || 1, strict: !!opts.viewing };
}

// Человек СМОТРИТ на эту вкладку: она активна, и окно приложения в фокусе.
//
// Взгляд считается прочтением только в мягком случае — когда ответ лёг, пока человек смотрел
// куда-то ещё. Тогда «переключиться на вкладку» это настоящее действие: он пришёл читать.
//
// Если же ответ лёг прямо перед открытой вкладкой, переключаться человеку неоткуда, и такой
// «взгляд» пришёл бы в тот же миг, в который встала пометка, — сторож снимал бы сам себя.
// Здесь остаётся единственное честное подтверждение: ответ человека.
function onViewed(st) {
  if (!st || !st.at || st.strict) return st || initial();
  return { ...st, at: 0, strict: false };
}

// Висит ли непрочитанное. Это и есть то, что держит перезапуск (см. restart.askable).
function isUnread(st) {
  return !!(st && st.at);
}

return { initial, reset, onHumanSend, onTurnEnd, onViewed, isUnread };

});
