'use strict';
// restart.js — самоперезапуск вкладки, когда её контекст заполнился.
// Спека: docs/superpowers/specs/2026-08-08-self-restart-design.md
//
// Сессия не может почистить себя, и снаружи нельзя понять, безопасно ли её чистить: «всё
// закоммичено» и «три файла разобраны наполовину» выглядят одинаково. Поэтому приложение не
// определяет момент, а СПРАШИВАЕТ агента, и тот отвечает тремя вещами: можно ли; куда положил
// эстафету; какой командой его перезапустить.
//
// Здесь только чистая логика — решение «пора спросить», текст просьбы и разбор ответа. Печать
// в pty, чтение расхода и сборка команды живут в main.js: их нельзя проверить тестом, а это
// можно, и цена ошибки высокая (перезапуск не вернуть).
(function (root, factory) {
  const api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.SWARM_RESTART = api;
})(typeof self !== 'undefined' ? self : this, function () {
  // Порог — настройка КАЧЕСТВА, а не страховка от переполнения. Проценты у нас отмерены от
  // точки автосжатия (statusline.ctxUsed делит занятое на полезную часть окна), так что 100%
  // — это момент, когда Клод сжимает разговор сам. Значит промах не смертелен: без нас
  // получится сегодняшнее поведение.
  //
  // 30% по умолчанию, потому что агент тупеет задолго до конца окна — в абсолюте это триста
  // тысяч токенов на миллионном окне. Верх диапазона оставлен для другого намерения: не
  // держать агента свежим, а просто не упереться в стену.
  const MIN_PCT = 15;
  const MAX_PCT = 75;
  const DEFAULT_PCT = 30;

  // «Не задано» и «задано нулём» — разные вещи, и путать их дорого: сюда приходит
  // localStorage.getItem, а он на несохранённой настройке возвращает null. Через Number(null)
  // это ноль, то есть самый агрессивный порог — новый человек получал бы 15% вместо 30%,
  // причём молча, потому что 15 — законное значение ползунка.
  function clampPct(n) {
    if (n == null || n === '') return DEFAULT_PCT;
    const v = Math.round(Number(n));
    if (!isFinite(v)) return DEFAULT_PCT;
    return Math.max(MIN_PCT, Math.min(MAX_PCT, v));
  }

  // Сколько работы вкладка должна сделать после старта, прежде чем её можно спрашивать.
  // Свежая сессия стартует НЕ с нуля: прочитала таск, спеку, CLAUDE.md, пару файлов — и на
  // миллионном окне уже может оказаться у низкого порога. Без этой защёлки вкладка начнёт
  // крутиться в перезапусках, не делая работы. При пороге 75% дыра не открывалась, при 30%
  // открывается.
  const MIN_UPTIME_MS = 15 * 60 * 1000;
  // Переспрос после «не сейчас», если агент не назвал свой срок. Он лучше знает, когда у него
  // будет отметка, — поэтому его срок в приоритете, а это лишь потолок молчания.
  const RETRY_MS = 20 * 60 * 1000;
  const RETRY_MAX_MS = 3 * 3600 * 1000;
  // Ответ ждём не бесконечно: агент мог зависнуть, уйти в долгий инструмент или просто
  // проигнорировать просьбу. Тогда НЕ перезапускаем — молча гасить нельзя, — а спрашиваем
  // заново позже.
  const ANSWER_WAIT_MS = 10 * 60 * 1000;

  // Сколько раз подряд можно спросить, не получив ответа. Причина молчания бывает неустранимой:
  // в режиме плана агент вообще не может писать файлы, в ручном — упирается в разрешение на
  // запись. Без потолка мы вечно, раз в двадцать минут, вставляли бы в разговор двадцать строк
  // просьбы — то есть переводили на них ровно тот контекст, который взялись сберечь.
  const MAX_SILENT = 3;
  // Заготовленный запуск ждёт освободившейся оболочки. Долго, потому что `/exit` из очереди
  // никуда не денется. Но не бесконечно: человек мог утром вычистить строку ввода, и тогда выхода
  // не будет вовсе.
  const PENDING_MS = 60 * 60 * 1000;
  // Экранный путь (Windows): `/exit` сам открывает меню команд Клода, и оно закрывает строку
  // режима — «мебели нет» сразу после набора всегда. Отсюда выдержка и требование увидеть уход
  // дважды, с промежутком.
  const EXIT_BLIND_MS = 10_000;
  const GONE_GAP_MS = 1000;
  // Сколько ждать строку запуска от вкладки после разрешения. Она приходит через рендерер (там
  // живёт ярлык разговора), и молчание рендерера не должно запирать фазу навсегда.
  const GRANT_WAIT_MS = 2 * 60 * 1000;
  // И сколько ждать покоя, чтобы разрешение исполнить. Столько же, сколько живёт сам ответ: он о
  // том состоянии вкладки, которое агент видел, когда отвечал, и через полчаса работы это уже
  // другая вкладка с другой недоделанной работой.
  const GRANT_CALM_MS = ANSWER_WAIT_MS;

  // Имя файла-ответа по id разговора. Нужно тому, кто нашей просьбы НЕ ВИДЕЛ: свежая сессия
  // узнаёт про самозвон одной строкой на старте (см. selfRestartNote в hooks/swarm-signal.mjs), а
  // имени с ключом вкладки у неё взяться негде — ключ знает приложение, а хук знает только id
  // разговора. Общее имя `.swarm-restart.json` для этого не годится: в папке с двумя вкладками
  // сворм его не читает (непонятно, чью сессию гасить), и зов уходил бы в тишину — молча, потому
  // что предупреждение об этом сворм пишет на вкладку, а не в разговор.
  //
  // Дубликат этой строки живёт в хуке (модулей приложения ему не видно) и сверяется тестом.
  function answerName(sessionId) {
    const sid = String(sessionId == null ? '' : sessionId).replace(/[^\w.-]/g, '_');
    return sid ? '.swarm-restart-' + sid + '.json' : '';
  }

  // --- автомат: одна функция на все решения -----------------------------------
  // Пять проходов ревью дали 38 замечаний, из них 35 — в main.js, и ни одного здесь. Разница не
  // в аккуратности: там эти же решения лежали пятнадцатью полями состояния и шестью десятками
  // разбросанных `if`, и каждый проход находил через них новый путь. Три прохода подряд правка
  // одного пути ломала соседний.
  //
  // Поэтому решает автомат, а main.js только исполняет. Фазы:
  //
  //   idle    — ждём порога;
  //   asked   — просьба напечатана, ждём файла с ответом;
  //   granted — агент разрешил, ждём тишины во вкладке, чтобы не гасить работающего;
  //   exiting — `/exit` напечатан, ждём, пока агент уйдёт из оболочки;
  //   muted   — молчим до конца этой сессии: спрашивать НЕКОМУ (агент не отвечает);
  //   done    — молчим, потому что спрашивать НЕ О ЧЕМ: работа во вкладке закончена. Снимает
  //             это новая работа — то есть человек, написавший вкладке (main.js).
  //
  // Ходы: { phase, at, askedAt, retryAt, silent, exitAt, goneSeen, prompt }
  function initial() {
    return { phase: 'idle', at: 0, askedAt: 0, retryAt: 0, silent: 0, exitAt: 0, goneSeen: 0, prompt: '' };
  }

  // Ушёл ли агент из вкладки. Три источника разной надёжности, и порядок важен:
  //   • открытый диалог — «на месте» при любых других признаках: строки режима при нём тоже нет,
  //     и принять это за уход означало бы напечатать запуск в рамку запроса;
  //   • `ps` (в оболочке пусто) — точный ответ, так на маке и линуксе;
  //   • экран — там, где `ps` нет. Догадка, поэтому с выдержкой и двумя подтверждениями врозь.
  function goneStep(state, sig) {
    const s = sig || {};
    const seen = state.goneSeen || 0;
    if (s.dialog) return { gone: false, goneSeen: 0 };
    if (s.shellBusy === false) return { gone: true, goneSeen: seen };
    if (s.shellBusy !== undefined) return { gone: false, goneSeen: 0 };
    if (state.exitAt && s.now - state.exitAt < EXIT_BLIND_MS) return { gone: false, goneSeen: seen };
    if (s.modeVisible) return { gone: false, goneSeen: 0 };
    // Второе подтверждение — не вторым вызовом, а спустя время. Иначе два опроса подряд по одному
    // и тому же кадру давали «дважды видели» на одной случайной перерисовке.
    if (!seen) return { gone: false, goneSeen: s.now };
    if (s.now - seen < GONE_GAP_MS) return { gone: false, goneSeen: seen };
    return { gone: true, goneSeen: seen };
  }

  // Один такт. Возвращает следующее состояние и ОДНО действие для main.js:
  //   ask · grant · exit · fire · drop · nothing
  // Плюс note — строка в журнал вкладки, если человеку стоит знать.
  function step(state, sig) {
    const st = { ...initial(), ...(state || {}) };
    const s = sig || {};
    const now = s.now || Date.now();

    if (st.phase === 'exiting') {
      const g = goneStep(st, s);
      st.goneSeen = g.goneSeen;
      if (g.gone) return { state: { ...st, phase: 'idle', goneSeen: 0 }, action: 'fire' };
      // Агент всё ещё на месте час спустя. Ждать дальше нельзя: он закроется когда-нибудь потом
      // (человек закроет сам, доработает свой инструмент), и тогда в освободившуюся оболочку
      // приехал бы наш запуск с ночной задачей. Отменяем именно здесь, пока агент ЖИВ: у пустой
      // оболочки отмена оставила бы вкладку без агента вовсе.
      //
      // Час — и для закрытия сигналом тоже, хотя оно обычно занимает миллисекунды. Короткий срок
      // здесь пробовали (полминуты) и убрали: он создаёт гонку, которой не было. Мы отменяем
      // перезапуск, стирая заготовленную строку, а агент дозакрывается секундой позже — и вкладка
      // остаётся голой оболочкой навсегда, потому что спрашивать разрешение больше не у кого, а
      // строку печатать уже нечем. Медленное закрытие бывает (агент гасит свои подпроцессы),
      // зависшее насмерть — почти нет, так что размен очевиден.
      if (now - (st.exitAt || 0) > PENDING_MS) {
        return {
          state: { ...initial(), silent: st.silent, retryAt: now + RETRY_MS },
          action: 'drop',
          note: 'агент так и не вышел — запуск отменён, вкладка осталась как была',
        };
      }
      return { state: st, action: 'nothing' };
    }

    // Дальше — только когда функция включена. Фаза exiting выше нарочно: `/exit` уже ушёл, и
    // снятая галочка не должна оставлять вкладку голой оболочкой.
    if (!s.enabled) return { state: st, action: 'nothing' };

    // Немота — это «больше НЕ СПРАШИВАЮ», и только. Положенный файл спрашивать не надо: он уже
    // ответ, читать его не стоит ничего, и игнорировать его значит объяснять человеку, почему
    // написанное чёрным по белому разрешение никого не заинтересовало.
    //
    // Немота от этого и снимается: в неё вкладка попадает, когда агент трижды не ответил (не может
    // писать файлы) или трижды не дожил до спокойного мига. Появившийся файл опровергает первое, а
    // разрешение, которое мы тут же исполним, — второе.
    if (st.phase === 'muted' || st.phase === 'done') {
      if (!s.answer || !s.hasBase) return { state: st, action: 'nothing' };
      const out = earlyStep(st, s, now);
      return out.stale ? { ...out, dropAnswer: true } : out;
    }

    if (st.phase === 'granted') {
      // Что держит исполнение прямо сейчас. Одной причиной и в порядке важности: журналу нужна та,
      // которую человек увидит на вкладке, а не список из пяти.
      const hold = grantHold(s);
      // Пока держит непрочитанное, часы разрешения стоят. Портится оно от того, что вкладка живёт
      // дальше — берётся за новое, узнаёт то, чего нет в записке. А эта вкладка не живёт: агент
      // сказал своё и молчит, и ждём мы не его, а человеческие глаза. Считай мы эти минуты, ночь
      // выглядела бы так: ответ лёг мимо глаз, разрешение через десять минут протухло, через
      // двадцать просьба заново — и до утра, по двадцать строк просьбы в час, ровно в тот контекст,
      // который мы взялись сберечь. А с остановленными часами утренний взгляд гасит вкладку сразу.
      //
      // Только со строкой запуска на руках: без неё у фазы свой, короткий срок, и заморозить его
      // значило бы ждать молчащий рендерер вечно.
      if (s.hasLine && hold === 'unread') return { state: { ...st, at: now }, action: 'nothing', hold };
      // Разрешение скоропортящееся, и портится оно ЦЕЛИКОМ, а не только пока мы ждём строку
      // запуска. Здесь стоял срок лишь на её ожидание, а дальше фаза ждала покоя сколько угодно:
      // агент мог написать ответ инструментом посреди хода и работать ещё три часа, или человек
      // утром дал вкладке новую задачу — и мы гасили её в первый спокойный миг, стартуя свежую
      // сессию с ночным промптом и запиской, которая давно не про эту вкладку. Всё сделанное за
      // эти часы уходило без эстафеты вообще.
      if (now - (st.at || 0) > GRANT_CALM_MS) {
        // Считаем это молчанием — с тем же потолком. Агент, который разрешает и тут же уходит
        // работать дольше срока годности, отвечает нам вежливо, но по существу так же
        // безрезультатно: круг «спросили — разрешил — не дождались» повторялся бы каждые полчаса
        // всю ночь, тратя на просьбы ровно тот контекст, который мы взялись сберечь.
        //
        // Кроме одного случая: разрешение пережидало САБАГЕНТОВ. Тогда вкладка не молчала и не
        // отвечала впустую — она работала, и держали её мы сами (закрывать с ними нельзя). Наказать
        // её за это немотой до утра значило бы выключить перезапуск ровно тем вкладкам, которым он
        // нужнее всех: чем больше вкладка гоняет фоновых агентов, тем быстрее пухнет её контекст.
        // Круг всё равно не бесконечен — переспрос отложен, а эстафету агент перепишет уже с их
        // ответами, ради чего протухание и заведено.
        //
        // Непрочитанного здесь нет намеренно: оно часы вообще останавливает (см. выше), потому что
        // вкладка при нём стоит и записке устареть не от чего.
        const silent = s.sub > 0 ? (st.silent || 0) : (st.silent || 0) + 1;
        if (silent >= MAX_SILENT) {
          return {
            state: { ...initial(), phase: 'muted', silent },
            action: 'drop',
            note: `разрешение на перезапуск устарело ${silent} раза подряд — больше не спрашиваю.`
              + ' Вкладка занята работой длиннее, чем живёт разрешение',
          };
        }
        return {
          state: { ...initial(), silent, retryAt: now + RETRY_MS },
          action: 'drop',
          note: s.sub > 0
            ? 'разрешение на перезапуск устарело, пока считали фоновые агенты — спрошу заново,'
              + ' и записку агент перепишет уже с их ответами'
            : `разрешение на перезапуск устарело${hold ? ' — ' + holdText(hold) : ', пока вкладка была занята'}.`
              + ' Спрошу заново',
        };
      }
      // Ждём строку запуска: её собирает main, получив от вкладки новый ярлык разговора (ярлык
      // хранит рендерер, и после перезапуска он обязан стать новым). Рендерер может и не ответить
      // — закрыли вкладку, чистый терминал, сбой, — и тогда без срока фаза заперла бы функцию для
      // этой вкладки навсегда, причём молча.
      if (!s.hasLine) {
        if (now - (st.at || 0) <= GRANT_WAIT_MS) return { state: st, action: 'nothing' };
        return {
          state: { ...initial(), silent: st.silent, retryAt: now + RETRY_MS },
          action: 'drop',
          note: 'перезапуск не сложился — вкладка осталась как была, попробую позже',
        };
      }
      // Строка есть — но исполняем только по спокойной вкладке, и проверять это надо ЗДЕСЬ, а не
      // только в момент вопроса. Между ними проходит до десяти минут, и вкладка успевает снова
      // взяться за работу: агент дописал ответ инструментом, не закончив ход, или человек утром
      // написал в неё сам. `/exit` уехал бы работающему агенту, а свежая сессия стартовала бы с
      // ночным промптом поверх начатого разговора.
      // Сабагенты держат ЖЁСТКО, и это не то же самое, что «вкладка занята». Claude запускает их
      // в фоне и спокойно стоит на приглашении, пока они считают: вкладка «готова» по всем нашим
      // признакам, хотя в ней крутится десяток чужих ходов. Закрой мы агента в такой миг — с ним
      // умрут и они, а с ними час работы, которого нет ни в одной эстафете: записка писалась,
      // когда сабагенты ещё не отчитались, и рассказать в ней было нечего.
      //
      // Поэтому рвать нельзя даже с разрешением на руках. Спросить при этом можно и нужно — в
      // просьбе про них сказано прямо (askText), и агент сам дождётся их и внесёт их ответы в
      // записку. Здесь же — последняя проверка на случай, если он этого не сделал: сабагентов
      // могли запустить и после ответа.
      // И непрочитанное держит здесь по той же причине, что и работа: между разрешением и его
      // исполнением проходит до десяти минут, а ночное разрешение доживает и до утра. Человек за
      // это время успевает написать во вкладку и получить ответ — снести её теперь значит
      // выбросить ровно тот ответ, ради которого пометка и заведена (см. unread.js).
      //
      // Причину отдаём наружу (`hold`), а не проглатываем. Это единственное место, где перезапуск
      // стоит МОЛЧА и подолгу: разрешение получено, человеку сказано «можно гасить», а вкладка
      // живёт дальше. Живьём это выглядело как зависшая функция — и разбиралось только чтением
      // журнала приложения задним числом.
      if (hold) return { state: st, action: 'nothing', hold };
      return { state: { ...st, phase: 'exiting', exitAt: now, goneSeen: 0 }, action: 'exit' };
    }

    if (st.phase === 'asked') {
      if (s.answer) return answerStep(st, s, now);
      if (now - (st.askedAt || 0) <= ANSWER_WAIT_MS) return { state: st, action: 'nothing' };
      const silent = (st.silent || 0) + 1;
      if (silent >= MAX_SILENT) {
        return {
          state: { ...initial(), phase: 'muted', silent },
          action: 'nothing',
          note: `на просьбу о перезапуске нет ответа ${silent} раза подряд — больше не спрашиваю.`
            + ' Похоже, агент не может записать файл: посмотрите режим разрешений вкладки',
        };
      }
      return {
        state: { ...initial(), silent, retryAt: now + RETRY_MS },
        action: 'nothing',
        note: 'ответа про перезапуск нет — оставляю как есть, спрошу позже',
      };
    }

    // Отсрочка ещё идёт — но агент мог передумать сам, см. earlyStep.
    if (st.retryAt && now < st.retryAt) {
      if (s.answer && s.hasBase) return earlyStep(st, s, now);
      return { state: st, action: 'nothing' };
    }

    // Отсрочка кончилась, а ответ лежит. Это тот же зов файлом, что и внутри отсрочки, и он не
    // менее законный: агент отвечает, когда освободился, а не когда истёк придуманный им срок.
    //
    // Живой случай (14.08): в 16:07 спросили, к 16:17 ответа не было — отсрочка на двадцать минут.
    // В 20:49 агент положил в файл разрешение с эстафетой и промптом, и оно лежало непрочитанным
    // часами: после истёкшего срока сворм в файл больше не смотрел, а просто ждал спокойного мига,
    // чтобы напечатать двадцать строк просьбы заново. Причём дождавшись — выбросил бы этот ответ
    // как залежавшийся и добавил ещё двадцать минут: разрешение не просто игнорировалось, оно
    // сгорало.
    //
    // Ни порога, ни времени работы, ни отсрочки: всё это причины НЕ НАЧИНАТЬ разговор самим (см.
    // askable), а здесь разговор начал не сворм. Файл кладут, когда перезапуск нужен, — и знать об
    // этом лучше тому, кто его кладёт: агент видит, что перестал держать нить, а человек видит
    // агента. Наш процент — лишь догадка о том же самом.
    let stale = false;
    if (s.answer && s.hasBase) {
      const early = earlyStep(st, s, now);
      // Неразобранный ответ (тик попал в середину записи) — тоже причина стоять: печатать просьбу
      // поверх ответа, который агент прямо сейчас пишет, значит просить его дважды об одном.
      if (!early.stale) return early;
      // А залежавшийся — не зов (см. earlyStep), и обычному пути он не помеха. Но пусть его
      // уберут: он лежит в чужом репозитории, светится в `git status` и читался бы каждые
      // полминуты, пока вкладка занята.
      stale = true;
    }

    // idle: пора ли спрашивать.
    if (!askable(st, s, now)) return { state: st, action: 'nothing', dropAnswer: stale };
    return { state: { ...st, phase: 'asked', askedAt: now }, action: 'ask', dropAnswer: stale };
  }

  // Надо ли читать файл ответа перед тактом. Решение, а не руки, поэтому живёт здесь — но отдельно
  // от step: файл читается ДО такта, и знать о нём автомату надо заранее.
  //
  // Читаем во всех фазах, кроме двух последних, и это ответ на прямой вопрос владельца: «сделать
  // максимально гибко, чтобы в любой момент можно было записать файл, и скрипт понял, что надо
  // перезапускать». Прежние оговорки — порог, отсрочка, немота — все были про НАШУ инициативу:
  // когда прилично влезть в чужой разговор с двадцатью строками просьбы. К лежащему файлу они
  // отношения не имеют: он уже написан, и стоит его чтение одной попытки открыть файл раз в
  // полминуты — обычно неудачной, потому что прочитанное мы стираем.
  //
  // Не читаем после разрешения (granted, exiting): там ответ уже принят и исполняется, а фаза
  // выхода вдобавок тактуется четыре раза в секунду.
  function wantsAnswer(state, o) {
    const st = { ...initial(), ...(state || {}) };
    const s = o || {};
    // Выключенная функция не гасит вкладки ничем, включая файл: галочка — тоже решение человека, и
    // она главнее записки в репозитории. Висящий вопрос при этом переживёт хоть сутки, и
    // разрешение по нему — тоже (см. answerStep).
    if (!s.enabled) return false;
    return st.phase === 'asked' || st.phase === 'idle' || st.phase === 'muted' || st.phase === 'done';
  }

  // Перейдён ли порог — то есть пора ли СПРАШИВАТЬ. К зову файлом отношения не имеет.
  function pctOver(s) {
    const pct = Number(s.pct);
    if (!isFinite(pct) || pct <= 0) return false;      // расхода нет — статуслайн молчит
    return pct >= clampPct(s.threshold);
  }

  // Ответ, пришедший вне круга «спросили — ответили»: агент положил его в файл сам, не дожидаясь
  // нашей просьбы. Бывает и внутри отсрочки, и после того, как она истекла (см. step).
  //
  // Отсрочка — это молчание по часам, и в этом её слабое место: срок агент называет ДО работы, то
  // есть угадывает. Сказал «через полчаса», освободился через десять минут, эстафету дописал — и
  // двадцать минут вкладка стоит с готовым разрешением, о котором никто не спросит. А если за эти
  // двадцать минут она взялась за новое, круг пойдёт заново, и так до утра.
  //
  // Позвать нас словами в разговоре агент не может, и это не недоделка: разговор для этих решений
  // не читается вовсе — разбор прозы однажды перезапустит вкладку не тем (см. askText). Значит зов
  // идёт тем же каналом, что и ответ, — файлом.
  //
  // Сигнал чистый, и уговора для него не нужно: прочитанный ответ мы стираем, поэтому во время
  // отсрочки файла нет и появиться ему больше не с чего. Просьба агенту про это говорит прямо.
  //
  // Отдельно от answerStep, потому что расходятся они как раз на отказе: там незаданный или
  // залежавшийся ответ ставит новую отсрочку, а здесь трогать срок нельзя — агент ничего не
  // сказал, и отодвигать из-за мусора уже обещанный переспрос значит терять вкладку молча.
  function earlyStep(st, s, now) {
    const { raw, mtime } = s.answer;
    // Залежавшийся файл — не зов. Взяться ему тут почти негде (наше удаление могло не пройти:
    // папка вкладки уехала, прав не хватило), но принять его за зов значит перезапустить вкладку
    // по ответу, который агент писал совсем про другой круг.
    //
    // `stale` наружу — чтобы звавший отличил «файла нет смысла ждать» от «ответ ещё пишется»: на
    // первом обычный путь продолжается, на втором стоит.
    if (!mtime || now - mtime > ANSWER_WAIT_MS) return { state: st, action: 'nothing', stale: true };
    // Неразобранное оставляем лежать, как и в answerStep: тик мог попасть в середину записи.
    const a = parseAnswer(raw);
    if (!a) return { state: st, action: 'nothing' };
    // Откуда пришёл зов — только для слов в журнале: «раньше срока» про истёкший срок сказать
    // нельзя, а человек читает эти строки, разбираясь, почему вкладка гаснет или стоит.
    const early = !!(st.retryAt && now < st.retryAt);
    const wasMuted = st.phase === 'muted';
    if (a.done) return { state: { ...initial(), phase: 'done' }, action: 'drop', note: 'сказал, что работа в этой вкладке закончена — больше не спрашиваю. Спрошу снова, когда вкладке дадут новую работу' };
    // Передумал в другую сторону — тоже его право: новый срок замещает прежний. Счётчик молчания
    // обнуляем, как и на обычном «не сейчас»: агент ответил, а счётчик — про неответы.
    if (!a.restart) {
      const mins = Math.round(a.retryMs / 60000);
      // Причину называем: у зова файлом она чаще всего «положили полразрешения» — без промпта или
      // без указателя на эстафету, — и человеку, который этот файл писал руками, надо понять, что
      // сворм его увидел и почему не поехал.
      const why = `«не сейчас» (${a.reason}) — переспрошу через ${mins} мин`;
      return {
        state: { ...initial(), retryAt: now + a.retryMs },
        action: 'drop',
        note: early ? `перенёс переспрос на ${mins} мин, не дожидаясь прежнего срока`
          : wasMuted ? `ответил сам, хотя я уже молчал: ${why}`
          : `сам сказал ${why}`,
      };
    }
    return {
      state: { ...initial(), phase: 'granted', at: now, prompt: a.prompt, handoff: a.handoff, text: a.text },
      action: 'grant',
      note: early ? 'освободился раньше срока и позвал перезапуск сам'
        : wasMuted ? 'позвал перезапуск сам, хотя я уже молчал по этой вкладке — принимаю'
        : 'позвал перезапуск сам — беру разрешение из файла, не спрашивая заново',
    };
  }

  // Ответ на столе. Отдельно от step только для читаемости — зовётся лишь из фазы asked.
  function answerStep(st, s, now) {
    const { raw, mtime } = s.answer;
    // Разрешение скоропортящееся, и считаем от «сейчас», а не от времени вопроса: залежавшийся
    // ответ написан ПОЗЖЕ вопроса, так что сравнение с вопросом его как раз пропускало. Случай
    // живой: функцию выключили с висящим вопросом, агент дописал ответ, через сутки включили — и
    // мы стёрли бы разговор, в котором с тех пор работали целый день.
    if (!mtime || now - mtime > ANSWER_WAIT_MS) {
      return {
        state: { ...initial(), silent: st.silent, retryAt: now + RETRY_MS },
        action: 'drop',
        note: 'ответ про перезапуск залежался — не перезапускаю, спрошу заново',
      };
    }
    const a = parseAnswer(raw);
    // Неразобранное НЕ выбрасываем: тик, попавший в середину записи (эстафета текстом — это
    // килобайты, и запись не мгновенна), уничтожал бы уже дописанный агентом ответ.
    if (!a) return { state: st, action: 'nothing' };
    if (a.done) return { state: { ...initial(), phase: 'done' }, action: 'drop', note: 'сказал, что работа в этой вкладке закончена — больше не спрашиваю. Спрошу снова, когда вкладке дадут новую работу' };
    if (!a.restart) {
      return {
        state: { ...initial(), retryAt: now + a.retryMs },
        action: 'drop',
        note: `сказал «не сейчас» (${a.reason}) — переспрошу через ${Math.round(a.retryMs / 60000)} мин`,
      };
    }
    // Разрешение есть. Счётчик молчания обнуляем: он про ПОДРЯД идущие неответы, иначе три
    // случайных промаха за ночь, между которыми агент отвечал, навсегда выключали бы функцию.
    return {
      state: { ...initial(), phase: 'granted', at: now, prompt: a.prompt, handoff: a.handoff, text: a.text },
      action: 'grant',
    };
  }

  // Что мешает исполнить уже полученное разрешение. Пусто — ничто, гасим.
  //
  // Проверки те же, что стояли одной строкой условия; порядок — от безнадёжного к проходящему само,
  // потому что наружу уходит ОДНА причина, и человеку нужна главная.
  function grantHold(s) {
    if (!agentPresent(s)) return 'gone';
    if (boxOpen(s)) return 'box';
    if (!turnOver(s)) return 'busy';
    if (s.sub > 0) return 'sub';
    if (s.unread) return 'unread';
    return '';
  }

  // Причина словами — для журнала приложения и вкладки. Держим здесь, рядом с решением: main
  // только печатает.
  const HOLD_TEXT = {
    gone: 'в оболочке нет агента',
    box: 'на вкладке открыт запрос — печатать в него нельзя',
    busy: 'вкладка снова работает',
    sub: 'считают фоновые агенты — закрывать вкладку вместе с ними нельзя',
    unread: 'на вкладке ответ, которого ты ещё не видел',
  };

  function holdText(hold) {
    return HOLD_TEXT[hold] || '';
  }

  // Есть ли в оболочке агент. Спрашивать и гасить — два решения, но условие у них одно: печатать
  // можно только в живого Клода. Раньше проверка стояла лишь у просьбы, а гасит-то `/exit` больше:
  // человек мог за время ожидания закрыть агента и запустить в той же оболочке npm test, и наш
  // `/exit` с Enter уезжал туда.
  //
  // `undefined` — Windows, где `ps` недоступен и «в оболочке пусто» нам не скажет никто; там
  // судим по мебели Клода на экране.
  function agentPresent(s) {
    if (s.shellBusy === false) return false;
    if (s.shellBusy === undefined && !s.modeVisible) return false;
    return true;
  }

  // Подходящий момент — это КОНЕЦ ХОДА, а не зелёная вкладка. Три состояния значат одно и то же:
  // агент отдал ход и больше ничего не делает.
  //   • «готов» — очевидное;
  //   • «ждёт» — ход закончен зовом к человеку. В сворме это НОРМАЛЬНЫЙ конец хода: вкладки
  //     прощаются строкой зова, то есть «готов» у них почти не бывает. Пока сюда пускали только
  //     «готов», агент разрешал перезапуск, прощался — и этим зовом сам себя запирал: перезапуск
  //     стоял с разрешением в руках, пока человек не ответит. Вживую это восемь минут, а ночью
  //     отвечать некому вовсе — и разрешение сгорало по сроку, трижды подряд, до немоты;
  //   • «работает в фоне» — ход тоже отдан, вкладку разбудит фоновая задача.
  // Не пускаем только настоящую работу. Открытая рамка (dialog) проверяется отдельно и по другой
  // причине: в неё нельзя печатать, что бы ни говорил статус.
  function turnOver(s) {
    if (s.status === 'ready' || s.status === 'waiting') return true;
    return s.status === 'running' && !!s.bg;
  }

  // Открыт ли на вкладке запрос, в который нельзя печатать. Три источника, и каждый видит своё:
  //   • dialog — рамка НАЙДЕНА на экране. Это скрёб, то есть догадка;
  //   • box — рамку видит ХУК: Клод объявляет событием и запрос разрешения, и коробку
  //     AskUserQuestion. Единственный источник, который не может её проглядеть;
  //   • kind — вкладка ждёт разрешения по любому из каналов.
  // Пока «ждёт» блокировало всё подряд, рамка была прикрыта дважды, и остальные источники были не
  // нужны. Теперь зов сквозь эту проверку проходит — и рамка осталась бы на одном скрёбе экрана.
  // Промахнись он (рамка уехала за край, чужая отрисовка), и наши двадцать строк с Enter уехали бы
  // В РАМКУ, то есть выбрали бы в ней ответ за человека.
  //
  // Коробка вопроса опаснее запроса разрешения, хотя выглядит безобиднее. Запрос разрешения от
  // скрёба прикрыт вторым концом — `kind`, — а вот коробка приходит тем же `kind: 'question'`, что
  // и обычный зов прозой, и отличить их по нему нельзя: зов печати не мешает, коробка съедает
  // Enter. Различает их только `box`, потому что зов — это конец хода в стенограмме, а коробка —
  // событие Клода. Судить по одному `kind` пришлось бы в одну из сторон: либо печатать в коробку,
  // либо не перезапускать вкладки сворма никогда, ведь они прощаются зовом всегда.
  function boxOpen(s) {
    return !!s.dialog || !!s.box || s.kind === 'permission';
  }

  // Пора ли спрашивать. Здесь собраны все причины НЕ спрашивать, и каждая — отдельный способ
  // навредить.
  function askable(st, s, now) {
    // Есть ли чем перезапускать. Спрашивать вкладку, которую мы всё равно не поднимем, — это не
    // впустую, это во вред: просьба в двадцать строк печатается В ЖИВОЙ разговор, агент тратит на
    // ответ ход и пишет эстафету в файл посреди чужого репозитория, а перезапуск потом упирается
    // в «не знаю, чем её запускать». И так каждые двадцать минут до утра: разрешение обнуляет
    // счётчик молчания, поэтому потолок, который такие круги обрывает, здесь не срабатывает
    // никогда. Без строки бывают три вкладки: чистый терминал, агент, набранный руками с самого
    // начала, и та, где агента сменили руками (см. session:forgetLaunch).
    if (!s.hasBase) return false;
    if (!pctOver(s)) return false;
    // Конец хода, а не «готов»: иначе вкладку, которая прощается зовом, мы не спросили бы никогда
    // — а это как раз те вкладки, ради которых всё и делалось (см. turnOver).
    if (!turnOver(s)) return false;
    // А агент-то там есть? «Готов» на пустой оболочке выглядит так же, как «готов» у отдохнувшего
    // агента, а снимок расхода живёт своей жизнью ещё три четверти часа после того, как Клода
    // закрыли руками. Без этой проверки двадцать строк просьбы уезжали бы в ШЕЛЛ, и он послушно
    // попытался бы их выполнить. `undefined` — Windows, там про процессы мы не знаем ничего.
    // Без этого просьба уезжала в ШЕЛЛ у всякого, кто закрыл агента руками: снимок расхода ещё три
    // четверти часа считается годным, статус читается «готов», и двадцать строк русской прозы
    // отправлялись шеллу на исполнение.
    if (!agentPresent(s)) return false;
    if (boxOpen(s)) return false;
    // На вкладке лежит ответ, которого человек ещё не видел (unread.js). Спрашивать разрешения
    // бессмысленно: агент его даст — изнутри разговора «сказано» и «услышано» неразличимы, он
    // видит свой ответ написанным и считает дело сделанным. Судить об этом может только
    // приложение, потому что только оно знает, куда человек смотрел.
    //
    // Ждём без срока давности, это решение владельца: «если я задал вопрос — значит я жду ответ,
    // и он повлияет на разработку; если я спросил и ушёл спать — моя вина». Поэтому пометку
    // снимает человек и только человек (взглядом на вкладку или ответом), а не часы.
    if (s.unread) return false;
    if (!s.uptimeMs || s.uptimeMs < MIN_UPTIME_MS) return false;
    if (st.retryAt && now < st.retryAt) return false;
    return true;
  }

  // Текст просьбы. Печатается в живую сессию, поэтому написан как обращение к агенту, а не как
  // техническое задание: он его читает целиком и отвечает по нему.
  //
  // Ответ идёт в ФАЙЛ, а не прозой в переписку: приложению нужен однозначный указатель и
  // команда, а разбор прозы — это гадание, которое однажды перезапустит вкладку не тем.
  //
  // Про наработки сказано отдельно от записки, и формат мы не диктуем НАРОЧНО. Записка живёт до
  // следующего запуска и умирает вместе со вкладкой (мы сами её и стираем — она лежит в чужом
  // репозитории). Значит она годится для «что дальше» и не годится для знания о задаче: развилок,
  // отвергнутых вариантов, грабель. Тем более что вкладка — не задача: человек чистит сессию руками
  // и берёт другую работу, и накопительный журнал, привязанный к вкладке, потащил бы в новую задачу
  // решения по старой — молча, под видом законного контекста.
  //
  // Куда это класть, знает не приложение, а процесс команды: у одних блок в трекере, у других файл
  // плана в репозитории. Поэтому просим не формат, а ПОРЯДОК: сохрани как положено у тебя и
  // дописывай, не переписывай. Само правило «писать в момент решения, а не в момент передачи» —
  // тоже не наше дело: это скиллы задачи, а перезапуск здесь лишь страховка на конце.
  //
  // Про хвосты РАЗГОВОРА сказано отдельным абзацем, потому что записка о работе их не ловит: и
  // «что сделано», и «на чём стоишь» — про репозиторий, а тут про людей.
  //   • Незаданный вопрос — цена сместившегося момента: вкладка, зовущая человека, раньше не
  //     гасилась вовсе (ждали «готов»), а теперь зов помехой не считается, иначе вкладки сворма,
  //     прощающиеся зовом всегда, не перезапускались бы никогда.
  //   • Отложенный разговор — «доделаем таск и обсудим» — не ловится ничем в принципе: в коде его
  //     нет, в задаче нет, живёт он только в переписке. Свежая сессия про обещание не знает, а
  //     человек его помнит и ждёт продолжения; хуже того, он и не поймёт, что агента подменили.
  // В обоих случаях спасти может только сам агент, и оба решения — его: придержать перезапуск
  // или переписать хвост в записку.
  function askText(o) {
    const opts = o || {};
    const pct = Math.round(Number(opts.pct) || 0);
    const file = String(opts.answerFile || '');
    const sub = Math.max(0, Math.round(Number(opts.sub) || 0));
    // Про сабагентов — только когда они есть, и это не экономия строк: в просьбе к агенту без
    // сабагентов этот абзац был бы указанием ждать того, чего нет.
    const subLines = sub ? [
      `Вижу, у тебя считают фоновые агенты (${sub}). Перезапуск они не переживут: закроются`,
      'вместе с тобой, и их работа пропадёт. Не бросай их — дождись и внеси их результат в',
      'записку, и только потом отвечай «можно». Если ждать долго — ответь «не сейчас» со сроком.',
      '',
    ] : [];
    return [
      `[сворм] Контекст этой вкладки заполнен на ${pct}% — дальше ты будешь хуже держать нить.`,
      'Хочу перезапустить тебя с чистой сессией. С ЭТОГО МОМЕНТА новые фоновые задачи и',
      'сабагентов заводить ЗАПРЕЩЕНО — дожидайся уже запущенных и отвечай, ничего нового не начиная.',
      '',
      'Критерий не «закончена ли задача логически» (ревью, чек-лист, серия правок, второй круг',
      'того же ревью — рвать можно посреди любого из них, они переживут разрыв через записку), а',
      '«прервётся ли СЕЙЧАС что-то, что уже стоило токенов и продолжить будет нельзя»: работают',
      'сабагенты, идёт прогон команды, теста или сборки, ты ждёшь ответа от внешнего вызова. Если',
      'ничего такого не в процессе — рви сразу, не дожидаясь конца задачи или «логической» точки.',
      '',
      'И отдельно про конец работы, потому что на этом уже спотыкались: если задача СДЕЛАНА или',
      'до конца осталось одно-два дешёвых действия — отвечай «закончено» (done: true), а НЕ',
      'отсрочку. Свежий ты получит промпт «продолжи» на готовое и пойдёт искать несуществующий',
      'остаток. Доделай здесь и оставь разговор человеку — он ещё не читал твой итог. После',
      '«закончено» я про эту вкладку молчу и переспрашивать не буду: спрошу заново, когда вы',
      'дадите ей новую работу.',
      '',
      'Если сейчас нельзя — так и скажи, и назови срок, через сколько переспросить. Освободишься',
      'раньше срока — не жди его: положи в тот же файл ответ «можно», и я увижу его сам в течение',
      'полминуты. Прочитанный ответ я стираю, так что файла там не будет — просто напиши заново.',
      '',
      'Если можно — сначала зафиксируй эстафету себе будущему: что сделано, на чём стоишь, что',
      'дальше и чем проверять. Положи её туда, где у тебя это принято (таск, файл, ветвь); если',
      'некуда — отдай текстом, я сохраню сам и подсуну свежей сессии. Коротко и точно — пересказ',
      'разговора не нужен.',
      '',
      'Наработки сохрани так, как предусмотрено твоим процессом: решения, развилки,',
      'отвергнутые варианты и грабли живут там, где живёт задача, а не в записке.',
      'Дописывай, а не переписывай: иначе через три перезапуска от размышлений первой сессии',
      'не останется ничего.',
      '',
      'И отдельно — хвосты РАЗГОВОРА, которых не видно в работе. Оба умирают вместе с этим',
      'разговором, если не переписать:',
      '  • ты о чём-то спросил человека, а ответа ещё нет — впиши вопрос в записку и задай его',
      '    заново, когда поднимешься: отвечать сюда будет уже некому;',
      '  • вы договорились вернуться к чему-то потом («доделаем таск и обсудим») — это тоже в',
      '    записку, своими словами: о чём спор, к чему пришли, что осталось решить.',
      '',
      ...subLines,
      `Ответ положи в ${file} одним JSON-объектом:`,
      '  restart  — true если можно, false если нет',
      '  done     — true, если работа закончена: спрашивать больше не о чем, я замолчу до новой',
      '             работы. Отсрочка для этого не годится — про доделанное я буду переспрашивать',
      '             до самого закрытия вкладки',
      '  retry    — через сколько минут переспросить: работа НЕ закончена, но сейчас нельзя',
      '  handoff  — где лежит эстафета: ссылка, номер таска или путь',
      '  text     — текст эстафеты, ЕСЛИ положить её было некуда',
      '  prompt   — КОРОТКИЙ промпт для свежей сессии: чем заняться и где записка. Печатается в',
      '             терминал, поэтому подробности — в text или в записку: длинный промпт мы',
      '             всё равно унесём в файл и заменим указателем на него',
      '',
      'Работу новую пока не начинай — ответь и жди.',
    ].join('\n');
  }

  // Ответ агента. Терпимо к обёрткам: агент может завернуть JSON в ```-заборчик или что-то
  // дописать вокруг. Разбираем самый большой объект в тексте — единственное, что не зависит
  // от аккуратности форматирования.
  function parseAnswer(raw) {
    const s = String(raw == null ? '' : raw);
    let obj = null;
    try { obj = JSON.parse(s); } catch (_) { /* не чистый JSON — ищем объект внутри */ }
    if (!obj || typeof obj !== 'object') {
      const from = s.indexOf('{');
      const to = s.lastIndexOf('}');
      if (from < 0 || to <= from) return null;
      try { obj = JSON.parse(s.slice(from, to + 1)); } catch (_) { return null; }
    }
    if (!obj || typeof obj !== 'object') return null;
    const go = obj.restart === true;
    const prompt = trimStr(obj.prompt, 2000);
    const handoff = trimStr(obj.handoff, 500);
    const text = trimStr(obj.text, 20000);
    // Третий ответ: «работа здесь закончена». Отсрочки для этого не хватало, и это была не
    // придирка к словам: доделанную вкладку сворм переспрашивал бы каждые двадцать минут до
    // самого её закрытия, а согласиться агент не может — перезапускать готовое нельзя, свежая
    // сессия получит «продолжи» на то, чего не осталось. Круг без выхода, и оба его участника
    // правы. Молчание тут не навсегда: его снимает новая работа во вкладке (main.js).
    if (!go && obj.done === true) return { restart: false, done: true, reason: 'done', retryMs: RETRY_MS };
    // «Можно» без промпта — это не разрешение, а полразрешения: перезапустить и не сказать
    // свежей сессии, что делать, хуже, чем не перезапускать вовсе.
    if (go && !prompt) return { restart: false, reason: 'no-prompt', retryMs: RETRY_MS };
    // «Можно, эстафеты нет» — та же дыра с другой стороны: промпт вроде «продолжай» без
    // записки и без указателя оставит свежую сессию ни с чем.
    if (go && !handoff && !text) return { restart: false, reason: 'no-handoff', retryMs: RETRY_MS };
    if (go) return { restart: true, prompt, handoff, text };
    return { restart: false, reason: 'later', retryMs: retryMsOf(obj.retry) };
  }

  function trimStr(v, max) {
    if (typeof v !== 'string') return '';
    return v.trim().slice(0, max);
  }

  // Срок переспроса от агента. Минуты, потому что так о времени говорят словами; всё, что
  // непохоже на число, — умолчание. Потолок в три часа: «спроси через сутки» это уже не
  // отсрочка, а отказ, и вкладка не должна замолчать на сутки из-за одной опечатки.
  // Пол так же нужен, как потолок, и по той же причине — только с другой стороны. «Спроси через
  // минуту» от агента, занятого длинной работой, означало бы двадцать строк просьбы в разговор
  // каждую минуту всю ночь: мы тратили бы на просьбы ровно тот контекст, который взялись сберечь,
  // и гнали бы его вверх, а не вниз.
  const RETRY_MIN_MS = RETRY_MS / 2;
  function retryMsOf(v) {
    const n = Number(v);
    if (!isFinite(n) || n <= 0) return RETRY_MS;
    return Math.min(RETRY_MAX_MS, Math.max(RETRY_MIN_MS, Math.round(n * 60 * 1000)));
  }

  // Промпт свежей сессии едет ОДНИМ аргументом. Эстафета приходит оттуда, куда пишет не
  // только наш агент (комментарий в таске, файл в общем дереве), поэтому команду от агента мы
  // не исполняем — мы берём из неё только текст и сами делаем из него аргумент. Без этого
  // «команда от агента» превращается в способ выполнить на машине что угодно.
  //
  // Кавычки — по семейству оболочки, а не «как принято». Строка печатается в настоящий шелл
  // вкладки, и на cmd.exe одинарная кавычка не значит ничего: `claude 'продолжи таск 215'`
  // доедет до Клода тремя аргументами, из которых первый — со кавычкой внутри. Ровно поэтому
  // launch-line.js разбирает семейства руками, а не пишет один синтаксис на всех.
  function quoteArg(text, family) {
    // Управляющие символы вычищаются до кавычек: перевод строки в НАБИРАЕМОЙ строке — это
    // Enter раньше времени, то есть половина промпта уедет в шелл отдельной командой.
    const clean = String(text == null ? '' : text)
      .replace(/[\x00-\x1f\x7f]+/g, ' ')
      .trim();
    if (!clean) return '';
    // cmd.exe: только двойные, а внутри они удваиваются. Знаки, которыми cmd подставляет и
    // перенаправляет (`%`, `&`, `|`, `<`, `>`, `^`), в кавычках уже безобидны, кроме `%`:
    // его убираем, потому что `%VAR%` раскрылось бы и внутри кавычек.
    if (family === 'cmd') return '"' + clean.replace(/%/g, ' ').replace(/"/g, '""') + '"';
    // PowerShell: одинарные, внутри удваиваются (обратный слэш там не экранирует).
    if (family === 'powershell') return "'" + clean.replace(/'/g, "''") + "'";
    if (family === 'posix') return "'" + clean.replace(/'/g, "'\\''") + "'";
    // Оболочка незнакомая (nushell, xonsh, elvish, что-то своё в $SHELL) — синтаксис экранирования
    // мы не знаем и не угадываем, launch-line.js в этом месте тоже не гадает. Двойные кавычки
    // понимают все, а всё, что внутри них у кого-нибудь да значит особое — кавычки, доллар,
    // обратные кавычки и слэш, — из промпта убираем. Кусок формулировки дороже сломанной команды.
    return '"' + clean.replace(/["$`\\]/g, ' ') + '"';
  }

  // Промпт свежей сессии мы ПЕЧАТАЕМ в оболочку вкладки — и это ставит ему потолок, которого у
  // текста в файле нет. Килобайты, отданные псевдотерминалу, однажды повесили приложение целиком
  // (BUG-pty-deadlock-2026-08-11.md); порции это лечат (pty-write.js), но вида не лечат: эхо
  // оболочки размажет длинный промпт на пол-экрана свежей вкладки — ровно то, от чего заведён
  // envPassing в launch-line.js.
  //
  // Значит длинный промпт — это не промпт, а эстафета, приехавшая не тем полем. Уносим его в
  // записку и печатаем указатель на неё; всё, что мы теряем, — одно чтение файла свежей сессией,
  // и она это чтение всё равно делает. 500 знаков — заведомо больше любого «продолжи таск 215» и
  // заведомо меньше пересказа состояния работы.
  const PROMPT_MAX = 500;
  function promptFits(prompt) {
    return String(prompt == null ? '' : prompt).length <= PROMPT_MAX;
  }

  // Чем стартовать сессию, у которой весь промпт уехал в записку. Своей задачи здесь нет — она
  // в записке, и указатель на неё допишет handoffPrompt.
  const PROMPT_CARRIED = 'Продолжай прерванную работу';

  // Промпт плюс указатель на записку. Одной функцией, потому что склейка двух фраз — то самое
  // место, где выходило «продолжай.. Эстафета лежит в …»: агент свой промпт точкой и кончает.
  function handoffPrompt(prompt, file) {
    const head = String(prompt == null ? '' : prompt).trim().replace(/[\s.,;!]+$/, '');
    const tail = `Эстафета лежит в ${file} — прочитай её первым делом.`;
    return head ? `${head}. ${tail}` : tail;
  }

  // Строка запуска: команда, собранная приложением (свой ярлык, свои флаги), плюс промпт
  // агента отдельным аргументом.
  function launchLine(base, prompt, family) {
    const b = String(base || '').trim();
    const arg = quoteArg(prompt, family);
    if (!b) return '';
    return arg ? b + ' ' + arg : b;
  }

  return {
    MIN_PCT, MAX_PCT, DEFAULT_PCT, MIN_UPTIME_MS, RETRY_MS, ANSWER_WAIT_MS,
    MAX_SILENT, PENDING_MS, EXIT_BLIND_MS, GONE_GAP_MS, GRANT_WAIT_MS, GRANT_CALM_MS, RETRY_MIN_MS,
    PROMPT_MAX, PROMPT_CARRIED,
    clampPct, initial, step, wantsAnswer, goneStep, askText, parseAnswer, retryMsOf, quoteArg, launchLine,
    answerName,
    promptFits, handoffPrompt,
    // Наружу — ради такта вне очереди: main.js будит автомат не на всякое шевеление вкладки, а
    // ровно когда та кончила ход, и «кончила ход» должно значить здесь и там одно и то же.
    turnOver,
    // И причина простоя словами: решение принимает автомат, печатает main.
    holdText,
  };
});
