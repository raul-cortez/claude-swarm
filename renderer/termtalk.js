'use strict';
// termtalk.js — «эти байты сказал ТЕРМИНАЛ, а не человек».
//
// Из xterm наружу (term.onData) идёт один поток, и в нём смешаны две совершенно разные вещи.
// Первая — то, что человек сделал руками: печать, вставка, стрелки, Enter, Ctrl+C. Вторая —
// служебная речь самого терминала, к человеку не относящаяся вовсе:
//   • доклады мыши. Клод включает отслеживание (1000/1002/1003/1006), и тогда КАЖДОЕ движение
//     указателя над вкладкой уходит в поток отдельным сообщением, не говоря о кликах и колесе;
//   • ответы на запросы приложения: кто ты (DA), где курсор (CPR), какого цвета фон (OSC),
//     какого размера окно, поддержан ли режим. Их приложение ЖДЁТ — не доехавший ответ ему
//     некем заменить;
//   • отметки прихода и ухода фокуса.
//
// Разница дорогая. Граница владения (гейт в renderer.js) держит печать в отданной вкладке и
// спрашивает человека, забрать ли её себе. Пока «печатью» считалось всё подряд, ночную вкладку
// нельзя было даже открыть: движение мыши над ней поднимало модалку, закрытая модалка тут же
// всплывала снова от следующего движения, а ответы терминала гейт придерживал и по «Отмене»
// выбрасывал. Ровно эту же границу main.js однажды уже проводил у себя — там мышь молча
// выключала отправку в телегу (см. detector.keyboardEvent).
//
// Кусок проверяется целиком, без разбора на части: onData зовут ровно раз на каждое
// отправленное терминалом сообщение, так что смеси «доклад мыши + клавиша» в одном куске не
// бывает. А если что-то не узналось — это печать: лишняя модалка человека раздражает, а
// пропущенная строка уезжает агенту, который работает без него.
(function (root, factory) {
  const api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.SWARM_TERMTALK = api;
})(typeof self !== 'undefined' ? self : this, function () {

// Доклад мыши. SGR (1006) и пиксельный SGR: ESC [ < параметры и M (нажали/двинули) или m
// (отпустили). urxvt (1015) — то же без «<». Финальные M и m у CSI не встречаются ни у одной
// клавиши, так что спутать их с печатью нельзя.
const MOUSE = /^\x1b\[<?[0-9;]*[Mm]$/;
// Старый формат (без 1006): ESC [ M и ТРИ сырых байта координат, которые бывают печатными.
// xterm шлёт его мимо onData (там он двоичный), но узнаём и его — цена одна строка.
const MOUSE_X10 = /^\x1b\[M[\s\S]{3}$/;
// Ответ на запрос приложения: DA1/DA2 (…c), DSR (…n, …R), DECRPM (…$y), размеры окна (…t).
// Клавиш с такими финалами нет — кроме F3 с модификатором (ESC [ 1;N R), а он неотличим от
// ответа «курсор в первой строке» и по буквам, и по смыслу разбора.
const REPLY = /^\x1b\[[?>]?[0-9;]*(?:\$y|[cnRt])$/;
// Ответ строкой: OSC (цвета, заголовок) до BEL или ST и DCS (DECRQSS) до ST.
const OSC = /^\x1b\][^\x1b\x07]*(?:\x07|\x1b\\)$/;
const DCS = /^\x1bP[\s\S]*\x1b\\$/;
// Фокус пришёл / ушёл (1004).
const FOCUS = /^\x1b\[[IO]$/;

function isTerminalTalk(data) {
  const s = String(data == null ? '' : data);
  if (!s) return false;
  return MOUSE.test(s) || MOUSE_X10.test(s) || REPLY.test(s) || OSC.test(s) || DCS.test(s)
    || FOCUS.test(s);
}

return { isTerminalTalk };
});
