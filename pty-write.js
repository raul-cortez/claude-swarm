'use strict';
// pty-write.js — как текст сворма попадает в оболочку вкладки. Порциями и по одной очереди.
// Разбор живого случая, с обоими стеками: BUG-pty-deadlock-2026-08-11.md
//
// Вкладка — настоящий псевдотерминал, и всё, что сворм ей говорит (строку запуска, просьбу про
// перезапуск, сообщение из телеграма, вашу вставку из буфера), он ПЕЧАТАЕТ туда, как с
// клавиатуры. Один синхронный write на несколько килобайт вешает приложение целиком — не
// вкладку, а весь интерфейс со всеми вкладками, намертво и со 100% CPU:
//
//   • оболочка на другом конце сама перерисовывает полученное обратно в терминал, и выхлопа
//     выходит кратно больше, чем ввода;
//   • очередь ВЫВОДА псевдотерминала переполняется, и оболочка встаёт на своём же flush — то
//     есть перестаёт читать ввод;
//   • очередь ВВОДА переполняется тоже, и наш write встаёт в ней;
//   • читатель у мастера один — мы сами, и мы в этот момент внутри этого самого write. Никто
//     не разомкнёт: мы не читаем именно потому, что пишем.
//
// Обойти это буфером побольше нельзя, и «писать асинхронно» тоже нельзя: у tty запись из цикла
// событий блокирующая по устройству (libuv держит терминалы в блокирующем режиме, чтобы вывод не
// рвался). Единственное, что размыкает тупик, — вернуть управление циклу МЕЖДУ порциями: он
// вычитает накопившийся вывод, оболочка сойдёт с flush и продолжит читать наш ввод.
//
// Отдельным модулем и под тестом, потому что цена ошибки здесь несоразмерна виду правки: порядок
// байтов в pty — это то, что агент считает набранным текстом, и один кусок, пролезший не в свою
// очередь, превращает промпт в мусор, а `\r` посреди него — в отправленную половину.

// Сколько байт уходит за один write. Очередь ввода tty маленькая (на macOS порядка килобайта), и
// кусок должен помещаться в её остаток даже когда она наполовину полна, иначе на этом куске мы и
// встанем. Мельчить незачем: порции идут по такту цикла, то есть десяток килобайт уезжает за
// единицы миллисекунд.
const CHUNK = 256;

// Длина в байтах UTF-8 без Buffer — модуль ничего не знает о среде, и его тест тоже.
function cpBytes(cp) {
  if (cp < 0x80) return 1;
  if (cp < 0x800) return 2;
  if (cp < 0x10000) return 3;
  return 4;
}

function byteLength(text) {
  let n = 0;
  for (const ch of String(text == null ? '' : text)) n += cpBytes(ch.codePointAt(0));
  return n;
}

// Резать по КОДОВЫМ ТОЧКАМ, а не по символам строки: половина сурогатной пары, отданная
// отдельным write, доедет до оболочки не буквой, а знаком вопроса — эмодзи из телеграма и любой
// текст за пределами базовой плоскости побились бы ровно на границах порций.
//
// Внутри последовательностей резать можно и нужно: pty склеивает байты обратно, и вставка,
// разорванная посередине, для оболочки ничем не отличается от настоящей вставки из буфера —
// та и приезжает в терминал порциями по килобайту.
function chunks(data, max) {
  const limit = Math.max(1, Number(max) || CHUNK);
  const out = [];
  let cur = '';
  let n = 0;
  for (const ch of String(data == null ? '' : data)) {
    const w = cpBytes(ch.codePointAt(0));
    if (n && n + w > limit) { out.push(cur); cur = ''; n = 0; }
    cur += ch;
    n += w;
  }
  if (cur) out.push(cur);
  return out;
}

// Насос: одна очередь на вкладку.
//
// Очередь нужна не для порядка порций одной печати, а для порядка ПЕЧАТЕЙ. Пока длинный текст
// уезжает по кускам, в ту же вкладку просится ещё кто-нибудь: Enter, который телеграм отправляет
// отдельно от текста; ваша клавиша; Escape по кнопке из чата. Написав напрямую, он встрял бы
// между кусками — то есть в середину чужого слова. Поэтому пишет только насос, а остальные
// складывают в хвост.
//
// `write(key, chunk)` — руки наружу: вернуть false (или бросить), если вкладки уже нет; тогда
// хвост выбрасывается, а не досылается в пустоту. `schedule` подменяется в тесте.
function makeWriter(opts) {
  const write = opts.write;
  const schedule = opts.schedule || setImmediate;
  const max = Math.max(1, Number(opts.max) || CHUNK);
  const queues = new Map();

  // write() либо честно возвращает true/false тем же тактом (нынешние синхронные вкладки),
  // либо отдаёт промис (частичная запись через fs.writeSync растягивается на несколько
  // тактов, pty-raw-write.js) — pump() не должен звать следующую порцию, пока предыдущая не
  // долетела: иначе куски одной печати обгонят друг друга в pty.
  function isThenable(v) { return !!v && typeof v.then === 'function'; }

  function send(key, chunk) {
    try { return write(key, chunk); } catch (_) { return false; }
  }

  // Одна порция за такт. Возвращает, ушла ли ЭТА порция: по первой из них вызывающий понимает,
  // напечатано ли вообще хоть что-то (вкладку могли закрыть за то время, пока текст готовился).
  // Для промиса это оптимистичное «передали в доставку» — окончательный исход синхронно
  // узнать нельзя, но такт на следующую порцию наступает только после его разрешения.
  function pump(key) {
    const parts = queues.get(key);
    if (!parts || !parts.length) { queues.delete(key); return false; }
    const result = send(key, parts.shift());
    if (isThenable(result)) {
      result.then(
        (ok) => { if (ok === false || !parts.length) queues.delete(key); else schedule(() => pump(key)); },
        () => queues.delete(key),
      );
      return true;
    }
    const ok = result !== false;
    if (!ok || !parts.length) { queues.delete(key); return ok; }
    schedule(() => pump(key));
    return true;
  }

  return {
    // Отдать текст вкладке. Возвращает false только если отдавать было нечего или первая же
    // порция не ушла — вызывающему это нужно, чтобы не считать напечатанным то, чего нет.
    push(key, data) {
      const parts = chunks(data, max);
      if (!parts.length) return false;
      const queued = queues.get(key);
      if (queued) { for (const p of parts) queued.push(p); return true; }
      // Одна порция и пустая очередь — обычный случай (нажатие клавиши, Escape, короткая
      // команда). Пишем сразу: ждать такта цикла набору текста незачем, а перегрузить очередь
      // tty парой сотен байт нечем.
      if (parts.length === 1) {
        const result = send(key, parts[0]);
        return isThenable(result) ? true : result !== false;
      }
      queues.set(key, parts);
      return pump(key);
    },
    // Вкладки больше нет: хвост выбросить. Иначе очередь мёртвой вкладки живёт до конца
    // приложения, а её порции стучатся в закрытый pty.
    drop(key) { queues.delete(key); },
    // Сколько порций ещё не ушло. Нужно тесту и разбору «а точно ли всё уехало».
    pending(key) { const p = queues.get(key); return p ? p.length : 0; },
  };
}

module.exports = { CHUNK, chunks, byteLength, makeWriter };
