'use strict';
// deadtab.js — вкладка, у которой умер АГЕНТ, а оболочка осталась жива.
//
// Это не то же самое, что смерть вкладки (там уходит сам шелл — см. session:exit в main.js).
// Здесь `claude` вышел или упал, а `zsh` остался стоять с приглашением: вкладка выглядит
// спокойной, статус сползает в «готов», и со стороны это неотличимо от вкладки, которая просто
// ничего не делает. Человек подходит к ней через час и не знает ни что случилось, ни о чём вообще
// была работа.
//
// Здесь — только арифметика и разбор текста: как отличить падение от честного выхода и чем
// погасить мышиный режим, застрявший после падения. Само наблюдение за деревом процессов и
// экраном живёт в main.js.
(function (root, factory) {
  const api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.SWARM_DEADTAB = api;
})(typeof self !== 'undefined' ? self : this, function () {
  // Чем оболочка сообщает, что задание убито сигналом. zsh печатает это одной строкой перед
  // следующим приглашением: `zsh: killed     claude --settings …`. Слова взяты из таблицы
  // сигналов zsh/bash; список закрытый нарочно — «что угодно после zsh:» ловило бы и обычные
  // жалобы оболочки («zsh: command not found»), а это не смерть агента.
  //
  // ⛔ Обычный ненулевой выход сюда НЕ попадает: на него оболочка молчит. То есть отсутствие
  // строки не доказывает, что всё прошло хорошо, — оно доказывает лишь, что процесс не убивали
  // сигналом. Второй признак падения (оборванный ход) считается снаружи, см. verdict.
  const SIGNAL_WORDS = [
    'killed',
    'terminated',
    'abort',
    'bus error',
    'segmentation fault',
    'floating point exception',
    'illegal hardware instruction',
    'trace/breakpoint trap',
  ];

  // `zsh: killed     claude …` — слово идёт сразу за именем оболочки. bash пишет иначе:
  // `…: line 12: 4242 Killed: 9  claude …`, поэтому вторым заходом ищем слово с большой буквы
  // после номера процесса. Регистр не важен ни там, ни там.
  const ZSH_RE = /^\s*(?:zsh|bash|sh|ksh):\s*([a-z/ ]+?)(?:\s{2,}|:\s|$)/i;
  const BASH_RE = /\b\d+\s+([A-Z][a-z/ ]+?)(?::\s*\d+)?\s{2,}/;

  function normWord(s) {
    const w = String(s || '').trim().toLowerCase().replace(/\s+/g, ' ');
    return SIGNAL_WORDS.includes(w) ? w : '';
  }

  // Слово смерти в нижних строках экрана вкладки. rows — массив строк снимка (main.js: snapshot).
  // Смотрим только НИЖНИЕ строки: выше по экрану то же слово может лежать куском старой
  // переписки — агент цитировал вывод, показывал пример, обсуждал этот самый баг.
  const LOOK_ROWS = 6;
  function shellDeathWord(rows) {
    const list = Array.isArray(rows) ? rows : String(rows || '').split('\n');
    for (const line of list.slice(-LOOK_ROWS)) {
      const m = ZSH_RE.exec(line);
      const w = m && normWord(m[1]);
      if (w) return w;
      const b = BASH_RE.exec(line);
      const bw = b && normWord(b[1]);
      if (bw) return bw;
    }
    return '';
  }

  // Что случилось со вкладкой на переходе «в оболочке было занято → пусто».
  //
  //   wasBusy/busy — тот самый переход (см. shellBusy в main.js). Оба должны быть известны:
  //     на первом такте после запуска wasBusy ещё undefined, и считать это уходом нельзя.
  //   word        — слово оболочки (shellDeathWord выше). Твёрдое доказательство падения.
  //   turnActive  — агент был в СЕРЕДИНЕ хода. Косвенный признак: руками `/exit` пишут, когда
  //                 агент молчит и ждёт, а не посреди его ответа.
  //   expected    — ухода ждали мы сами (самоперезапуск печатает `/exit`, вкладку закрывают).
  //                 Тогда это вообще не событие: никакой тревоги, никакого предложения поднять.
  // Тот самый переход, и ничего больше. Отдельно от verdict, потому что зовущий обязан узнать
  // о переходе ДО того, как полезет читать экран: без этого снимок терминала снимался бы на
  // каждом такте у каждой вкладки ради ответа «ничего не случилось».
  function leftShell(wasBusy, busy) {
    return wasBusy === true && busy === false;
  }

  function verdict(sig) {
    const s = sig || {};
    if (!leftShell(s.wasBusy, s.busy)) return { gone: false, how: null, why: null };
    if (s.expected) return { gone: true, how: 'quit', why: null };
    if (s.word) return { gone: true, how: 'crash', why: 'signal' };
    if (s.turnActive) return { gone: true, how: 'crash', why: 'midturn' };
    return { gone: true, how: 'quit', why: null };
  }

  // Как назвать случившееся человеку на карточке. Коротко: это подпись под именем вкладки,
  // рядом с ней живут «готов» и «думает».
  function goneLabel(how, why, word) {
    if (how !== 'crash') return '';
    if (why === 'signal') return 'агент убит: ' + (word || 'сигнал');
    return 'агент исчез на ходу';
  }

  // Чем погасить мышиный режим и прочее наследство упавшего агента.
  //
  // ⛔ Это пишется В ЭМУЛЯТОР (term.write в рендерере), а НЕ в pty. Мусор вида `35;57;4M`
  // сыплется потому, что xterm.js всё ещё считает мышиный режим включённым и шлёт события мыши
  // в стандартный ввод оболочки, а та их печатает. Гасить надо того, кто шлёт, — сам эмулятор.
  // Та же строка, отправленная в pty, ушла бы zsh в поле ввода отдельной порцией мусора.
  //
  // Гасим ровно то, что включает под собой полноэкранный агент: все виды слежения за мышью
  // (1000/1002/1003 и кодировки 1005/1006/1015), «скобочную вставку» (2004) и запасной экран
  // (1049). Плюс возвращаем курсор (25h) и обычные атрибуты (0m): упасть можно и со спрятанным
  // курсором, и посреди раскраски.
  const RESET_SEQ = '\x1b[?1000l\x1b[?1002l\x1b[?1003l\x1b[?1005l\x1b[?1006l\x1b[?1015l'
    + '\x1b[?2004l\x1b[?1049l\x1b[?25h\x1b[0m';

  return { SIGNAL_WORDS, LOOK_ROWS, RESET_SEQ, shellDeathWord, leftShell, verdict, goneLabel };
});
