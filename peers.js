'use strict';
// peers.js — ВИЗИТКА ВКЛАДКИ ДЛЯ СОСЕДЕЙ: что одна сессия может узнать о другой, не спрашивая.
// Спека: docs/superpowers/specs/2026-09-10-peer-identity-design.md
//
// Зачем это вообще понадобилось. Агент видит соседние сессии списком, и в списке у вкладки
// есть ровно одно поле — имя, которое выдаём мы сами (renderer/resume.js, newSessionKey).
// Пока в нём был голый хекс, вкладки-прорабы дважды за полчаса раздали задачи в чужие
// репозитории: `swarm-267a6161` не говорит ни про проект, ни про занятость. Одна успела
// завести ворктри и откатить статус задачи, прежде чем поняла, что работает не там.
//
// Имя проекта теперь в ключе, и этого хватает для «чья вкладка». Не хватает для всего
// остального, и по принципиальной причине: `-n` ставится РОВНО ОДИН РАЗ, при запуске. Мандат
// «работай без меня» человек отдаёт и забирает поодиночке в любой момент (night.js, d.auto),
// занятость меняется каждый ход. Имя, в которое вписано изменчивое, к утру врёт — вкладку
// вернули себе три часа назад, а список всё ещё зовёт её ночной. Поэтому изменчивое живёт
// в файле, который переписывается, а не в имени, которое прибито гвоздём.
//
// Всё это сворм уже знает: и мандат, и статус, и дайджест («чем занят сейчас») лежат в его
// состоянии вкладки. Наружу не выходило ничего — данные есть и свежие, а агенту недоступны.
// Модуль ровно об этом: превратить состояние в строки, которые не стыдно показать соседу.
//
// Чистый, без Electron и без fs, по той же причине, что night.js и restart.js: решение «что
// показывать» проверяемо тестом, а запись на диск — нет.

// РЕЕСТР ТОЛЬКО РАССКАЗЫВАЕТ. Ни «занять вкладку», ни блокировок, ни очереди здесь не будет,
// и это ограничение, а не недоделка. Стоит разрешить запись — и придётся отвечать на гонку
// двух прорабов, на протухшую блокировку и на вкладку, умершую с захваченной задачей. Раздаёт
// работу по-прежнему человек или прораб, обычным сообщением; реестр помогает не ошибиться
// адресом, а не заменяет разговор.

// Дайджест в реестре обрезаем короче, чем на карточке. Читатель здесь другой: карточку
// человек разглядывает по одной, а реестр агент читает целиком, десятью строками разом,
// и платит за него контекстом. Хватает первой фразы — «чем вкладка занята», а не всего
// рассказа; кому нужны подробности, тот напишет вкладке и спросит.
const DIGEST_MAX = 120;

function short(text, max) {
  const s = String(text == null ? '' : text).replace(/\s+/g, ' ').trim();
  if (s.length <= max) return s;
  return s.slice(0, max - 1).replace(/[\s,;:.—-]+$/, '') + '…';
}

// Имя проекта — тот же basename, что попал в ключ сессии, но БЕЗ санитайзера resume.js.
// Там он резал строку под командную строку (латиница, 16 знаков), здесь ограничения нет:
// это поле читают глазами, и кириллический каталог должен называться как называется.
function projectOf(cwd) {
  return String(cwd || '').trim().replace(/[\\/]+$/, '').split(/[\\/]/).pop() || '';
}

// Одна строка реестра. `d` — состояние вкладки из main (det).
//
// Первые три поля — те, что здесь были и раньше (swarm-tabs.json как дисковая копия связки
// «ярлык → текущий разговор» для разбора после жёсткого креша). Их имена и смысл не трогаем:
// у файла уже есть обязанность, и новая её не отменяет.
function row(d) {
  return {
    cwd: d.cwd || '',
    sessionKey: d.sessionKey || '',
    claudeSessionId: d.claudeSessionId,
    // --- визитка -------------------------------------------------------------
    project: projectOf(d.cwd),
    // Ярлык вкладки — то, как её зовёт ВЛАДЕЛЕЦ. Прораб, которому надо написать человеку
    // «твоя вкладка Фастио 686 стоит на вопросе», без этого поля может назвать её только
    // хексом, и человек не поймёт, о какой речь.
    tab: d.name || '',
    // Мандат «работай без меня». Главное поле для того, кто раздаёт работу: вкладке без
    // мандата задачу на ночь давать бессмысленно — она встанет на первом же вопросе.
    auto: !!d.auto,
    // 'ready' | 'running' | 'waiting' — то же, что цвет карточки (detector.js).
    // 'waiting' здесь важнее 'running': вкладка, стоящая на вопросе, выглядит занятой, а на
    // деле её работа стоит и ждёт человека. По списку это должно быть видно без домыслов.
    status: d.status || '',
    detail: d.detail || '',
    digest: short(d.digestText, DIGEST_MAX),
  };
}

// Весь реестр: id вкладки → визитка.
//
// Мёртвых не пишем. Вкладка, чей агент упал, в списке агентов уже не отвечает, и строка о
// ней — приглашение отправить задачу в пустоту. `dead` сворм проставляет сам (deadtab.js).
//
// Без id разговора тоже не пишем: такую вкладку соседи всё равно не найдут — ни по имени в
// списке, ни по файлам хука, которые именуются от этого id.
function rows(entries) {
  const out = {};
  for (const [id, d] of entries) {
    if (!d || d.dead || !d.claudeSessionId) continue;
    out[id] = row(d);
  }
  return out;
}

module.exports = { rows, row, projectOf, short, DIGEST_MAX };
